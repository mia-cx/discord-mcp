import { fileURLToPath } from 'node:url'
import { and, desc, eq, isNotNull, isNull, sql } from 'drizzle-orm'
import type { PgDatabase, PgQueryResultHKT } from 'drizzle-orm/pg-core'
import type { Storage, WorkflowChange, WorkflowRevision } from './index.ts'
import type { AdvisoryLocks } from './locks.ts'
import * as schema from './schema.ts'

/** Drizzle wraps driver errors in "Failed query"; the driver's own message says what went wrong. */
export const rootMessage = (error: unknown): string =>
  error instanceof Error && error.cause !== undefined ? rootMessage(error.cause) : String(error)

/** Checked-in SQL generated by `pnpm --filter @discord-mcp/storage generate`. */
export const migrationsFolder = fileURLToPath(new URL('../drizzle', import.meta.url))

type Db = PgDatabase<PgQueryResultHKT, typeof schema>

const { workflows, workflowRevisions: revisions, workflowChanges: changes } = schema

const revisionColumns = {
  botId: workflows.botId,
  name: workflows.name,
  revision: revisions.revision,
  source: revisions.source,
  grants: revisions.grants,
  events: revisions.events,
  intents: revisions.intents,
  schedules: revisions.schedules,
  publishedBy: revisions.publishedBy,
  publishedAt: revisions.publishedAt,
}

const record = (
  db: Db,
  botId: string,
  change: Pick<WorkflowChange, 'workflowName' | 'action' | 'revision' | 'actorId'>,
) => db.insert(changes).values({ botId, ...change })

/** Advisory lock names, so other locks can never collide with the scheduler's. */
const scheduleLock = (botId: string) => `textile-schedules:${botId}`

export const createStorage = (
  db: Db,
  locks: AdvisoryLocks,
  close: () => Promise<void>,
): Storage => ({
  storeSealedToken: async (botId, sealedToken) => {
    try {
      await db
        .insert(schema.bots)
        .values({ id: botId, sealedToken })
        .onConflictDoUpdate({ target: schema.bots.id, set: { sealedToken, updatedAt: sql`now()` } })
    } catch (cause) {
      // Drizzle's own message lists the query parameters, sealed token included.
      throw new Error(`Storing bot ${botId}'s token failed: ${rootMessage(cause)}`)
    }
  },
  loadSealedToken: async (botId) => {
    const [row] = await db
      .select({ sealedToken: schema.bots.sealedToken })
      .from(schema.bots)
      .where(eq(schema.bots.id, botId))
    return row?.sealedToken
  },
  storeSealedSession: async (botId, shardId, sealedSession) => {
    try {
      await db
        .insert(schema.shardSessions)
        .values({ botId, shardId, sealedSession })
        .onConflictDoUpdate({
          target: [schema.shardSessions.botId, schema.shardSessions.shardId],
          set: { sealedSession, updatedAt: sql`now()` },
        })
    } catch (cause) {
      throw new Error(
        `Storing bot ${botId}'s shard ${shardId} session failed: ${rootMessage(cause)}`,
      )
    }
  },
  deleteSession: async (botId, shardId) => {
    await db
      .delete(schema.shardSessions)
      .where(and(eq(schema.shardSessions.botId, botId), eq(schema.shardSessions.shardId, shardId)))
  },
  loadSealedSessions: () =>
    db
      .select({
        botId: schema.shardSessions.botId,
        shardId: schema.shardSessions.shardId,
        sealedSession: schema.shardSessions.sealedSession,
        sealedToken: schema.bots.sealedToken,
      })
      .from(schema.shardSessions)
      .innerJoin(schema.bots, eq(schema.bots.id, schema.shardSessions.botId)),

  publishWorkflow: ({ actorId, botId, name, ...revision }) =>
    db.transaction(async (tx) => {
      // The upsert locks the workflow's row, so concurrent publishes number their revisions in turn.
      const [workflow] = await tx
        .insert(workflows)
        .values({ botId, name, latestRevision: 1 })
        .onConflictDoUpdate({
          target: [workflows.botId, workflows.name],
          set: { latestRevision: sql`${workflows.latestRevision} + 1`, updatedAt: sql`now()` },
        })
        .returning({ id: workflows.id, revision: workflows.latestRevision })
      if (workflow === undefined) throw new Error(`Publishing workflow ${name} stored nothing.`)
      const [stored] = await tx
        .insert(revisions)
        .values({
          workflowId: workflow.id,
          revision: workflow.revision,
          publishedBy: actorId,
          ...revision,
        })
        .returning({ publishedAt: revisions.publishedAt })
      await record(tx, botId, {
        workflowName: name,
        action: 'publish',
        revision: workflow.revision,
        actorId,
      })
      return {
        botId,
        name,
        revision: workflow.revision,
        publishedBy: actorId,
        publishedAt: stored?.publishedAt ?? new Date(),
        ...revision,
      }
    }),

  listWorkflows: (botId) =>
    db
      .select({
        name: workflows.name,
        latestRevision: workflows.latestRevision,
        enabledRevision: workflows.enabledRevision,
      })
      .from(workflows)
      .where(eq(workflows.botId, botId))
      .orderBy(workflows.name),

  loadWorkflowRevision: async (botId, name, revision) => {
    const [row] = await db
      .select(revisionColumns)
      .from(revisions)
      .innerJoin(workflows, eq(workflows.id, revisions.workflowId))
      .where(
        and(
          eq(workflows.botId, botId),
          eq(workflows.name, name),
          eq(revisions.revision, revision ?? workflows.latestRevision),
        ),
      )
    return row
  },

  setEnabledRevision: (botId, name, revision, actorId) =>
    db.transaction(async (tx) => {
      const workflow = and(eq(workflows.botId, botId), eq(workflows.name, name))
      const [updated] = await tx
        .update(workflows)
        .set({ enabledRevision: revision, scheduleCursor: null, updatedAt: sql`now()` })
        .where(
          revision === null
            ? workflow
            : and(workflow, sql`${revision} between 1 and ${workflows.latestRevision}`),
        )
        .returning({ id: workflows.id })
      if (updated === undefined) return false
      await record(tx, botId, {
        workflowName: name,
        action: revision === null ? 'disable' : 'enable',
        revision,
        actorId,
      })
      return true
    }),

  deleteWorkflow: (botId, name, actorId) =>
    db.transaction(async (tx) => {
      const [deleted] = await tx
        .delete(workflows)
        .where(and(eq(workflows.botId, botId), eq(workflows.name, name)))
        .returning({ id: workflows.id })
      if (deleted === undefined) return false
      await record(tx, botId, { workflowName: name, action: 'delete', revision: null, actorId })
      return true
    }),

  enabledRevisions: (botId): Promise<ReadonlyArray<WorkflowRevision>> =>
    db
      .select(revisionColumns)
      .from(revisions)
      .innerJoin(
        workflows,
        and(
          eq(workflows.id, revisions.workflowId),
          eq(workflows.enabledRevision, revisions.revision),
        ),
      )
      .where(
        botId === undefined ? isNotNull(workflows.enabledRevision) : eq(workflows.botId, botId),
      )
      .orderBy(workflows.botId, workflows.name),

  workflowChanges: (botId, limit) =>
    db
      .select({
        workflowName: changes.workflowName,
        action: changes.action,
        revision: changes.revision,
        actorId: changes.actorId,
        at: changes.at,
      })
      .from(changes)
      .where(eq(changes.botId, botId))
      .orderBy(desc(changes.id))
      .limit(limit),

  scheduledWorkflows: (botId) =>
    db
      .select({
        botId: workflows.botId,
        name: workflows.name,
        revision: revisions.revision,
        schedules: revisions.schedules,
        cursor: workflows.scheduleCursor,
      })
      .from(revisions)
      .innerJoin(
        workflows,
        and(
          eq(workflows.id, revisions.workflowId),
          eq(workflows.enabledRevision, revisions.revision),
        ),
      )
      .where(
        and(
          sql`jsonb_array_length(${revisions.schedules}) > 0`,
          botId === undefined ? undefined : eq(workflows.botId, botId),
        ),
      )
      .orderBy(workflows.botId, workflows.name),

  advanceScheduleCursor: async ({ botId, name, revision }, from, to) => {
    const [advanced] = await db
      .update(workflows)
      .set({ scheduleCursor: to })
      .where(
        and(
          eq(workflows.botId, botId),
          eq(workflows.name, name),
          eq(workflows.enabledRevision, revision),
          from === null ? isNull(workflows.scheduleCursor) : eq(workflows.scheduleCursor, from),
        ),
      )
      .returning({ id: workflows.id })
    return advanced !== undefined
  },

  lockSchedules: (botId) => locks.lock(scheduleLock(botId)),
  unlockSchedules: (botId) => locks.unlock(scheduleLock(botId)),

  close: async () => {
    await locks.close()
    await close()
  },
})
