import { fileURLToPath } from 'node:url'
import { and, desc, eq, gte, isNotNull, lt, lte, ne, sql } from 'drizzle-orm'
import type { PgDatabase, PgQueryResultHKT } from 'drizzle-orm/pg-core'
import type { Storage, VoiceOptOutChange, WorkflowChange, WorkflowRevision } from './index.ts'
import type { AdvisoryLocks } from './locks.ts'
import * as schema from './schema.ts'

/** Drizzle wraps driver errors in "Failed query"; the driver's own message says what went wrong. */
export const rootMessage = (error: unknown): string =>
  error instanceof Error && error.cause !== undefined ? rootMessage(error.cause) : String(error)

/**
 * `query`, failing with only the driver's message. Drizzle's own lists the query parameters,
 * which hold what workflows wrote: KV keys and values, and run logs.
 */
const failing = <A>(what: string, query: PromiseLike<A>): Promise<A> =>
  Promise.resolve(query).catch((cause: unknown) => {
    throw new Error(`${what} failed: ${rootMessage(cause)}`)
  })

/** Checked-in SQL generated by `pnpm --filter @discord-mcp/storage generate`. */
export const migrationsFolder = fileURLToPath(new URL('../drizzle', import.meta.url))

type Db = PgDatabase<PgQueryResultHKT, typeof schema>

const {
  workflows,
  workflowRevisions: revisions,
  workflowChanges: changes,
  workflowKv: kv,
  workflowRuns: runs,
  voiceOptOuts,
  voiceGlobalOptOuts,
} = schema

const revisionColumns = {
  workflowId: workflows.id,
  botId: workflows.botId,
  name: workflows.name,
  revision: revisions.revision,
  source: revisions.source,
  bundle: revisions.bundle,
  packages: revisions.packages,
  grants: revisions.grants,
  events: revisions.events,
  intents: revisions.intents,
  schedules: revisions.schedules,
  publishedBy: revisions.publishedBy,
  publishedAt: revisions.publishedAt,
}

const record = (
  db: Db,
  botId: string,
  change: Pick<WorkflowChange, 'workflowName' | 'action' | 'revision' | 'actorId'>,
) => db.insert(changes).values({ botId, ...change })

/** Advisory lock names, so other locks can never collide with the scheduler's. */
const scheduleLock = (botId: string) => `textile-schedules:${botId}`

/** The Postgres notification channel that carries voice opt-out changes between processes. */
const VOICE_OPT_OUTS_CHANNEL = 'voice_opt_outs'

/**
 * Listen on a Postgres notification channel through the driver, hearing each payload. Resolves to
 * a function that stops listening.
 */
export type Listen = (
  channel: string,
  handlers: {
    readonly payload: (payload: string) => void
    /** Listening after a failed or lost connection, which missed what was sent meanwhile. */
    readonly resumed: () => void
    readonly lost: (error: Error) => void
  },
) => Promise<() => Promise<void>>

export const createStorage = (
  db: Db,
  locks: AdvisoryLocks,
  close: () => Promise<void>,
  listen: Listen,
): Storage => ({
  storeSealedToken: async (botId, sealedToken) => {
    try {
      await db
        .insert(schema.bots)
        .values({ id: botId, sealedToken })
        .onConflictDoUpdate({ target: schema.bots.id, set: { sealedToken, updatedAt: sql`now()` } })
    } catch (cause) {
      // Drizzle's own message lists the query parameters, sealed token included.
      throw new Error(`Storing bot ${botId}'s token failed: ${rootMessage(cause)}`)
    }
  },
  loadSealedToken: async (botId) => {
    const [row] = await db
      .select({ sealedToken: schema.bots.sealedToken })
      .from(schema.bots)
      .where(eq(schema.bots.id, botId))
    return row?.sealedToken
  },
  storeSealedSession: async (botId, shardId, sealedSession) => {
    try {
      await db
        .insert(schema.shardSessions)
        .values({ botId, shardId, sealedSession })
        .onConflictDoUpdate({
          target: [schema.shardSessions.botId, schema.shardSessions.shardId],
          set: { sealedSession, updatedAt: sql`now()` },
        })
    } catch (cause) {
      throw new Error(
        `Storing bot ${botId}'s shard ${shardId} session failed: ${rootMessage(cause)}`,
      )
    }
  },
  deleteSession: async (botId, shardId) => {
    await db
      .delete(schema.shardSessions)
      .where(and(eq(schema.shardSessions.botId, botId), eq(schema.shardSessions.shardId, shardId)))
  },
  loadSealedSessions: () =>
    db
      .select({
        botId: schema.shardSessions.botId,
        shardId: schema.shardSessions.shardId,
        sealedSession: schema.shardSessions.sealedSession,
        sealedToken: schema.bots.sealedToken,
      })
      .from(schema.shardSessions)
      .innerJoin(schema.bots, eq(schema.bots.id, schema.shardSessions.botId)),

  publishWorkflow: ({ actorId, botId, name, ...revision }) =>
    db.transaction(async (tx) => {
      // The upsert locks the workflow's row, so concurrent publishes number their revisions in turn.
      const [workflow] = await tx
        .insert(workflows)
        .values({ botId, name, latestRevision: 1 })
        .onConflictDoUpdate({
          target: [workflows.botId, workflows.name],
          set: { latestRevision: sql`${workflows.latestRevision} + 1`, updatedAt: sql`now()` },
        })
        .returning({ id: workflows.id, revision: workflows.latestRevision })
      if (workflow === undefined) throw new Error(`Publishing workflow ${name} stored nothing.`)
      const [stored] = await tx
        .insert(revisions)
        .values({
          workflowId: workflow.id,
          revision: workflow.revision,
          publishedBy: actorId,
          ...revision,
        })
        .returning({ publishedAt: revisions.publishedAt })
      await record(tx, botId, {
        workflowName: name,
        action: 'publish',
        revision: workflow.revision,
        actorId,
      })
      return {
        workflowId: workflow.id,
        botId,
        name,
        revision: workflow.revision,
        publishedBy: actorId,
        publishedAt: stored?.publishedAt ?? new Date(),
        ...revision,
      }
    }),

  listWorkflows: (botId) =>
    db
      .select({
        name: workflows.name,
        latestRevision: workflows.latestRevision,
        enabledRevision: workflows.enabledRevision,
      })
      .from(workflows)
      .where(eq(workflows.botId, botId))
      .orderBy(workflows.name),

  loadWorkflowRevision: async (botId, name, revision) => {
    const [row] = await db
      .select(revisionColumns)
      .from(revisions)
      .innerJoin(workflows, eq(workflows.id, revisions.workflowId))
      .where(
        and(
          eq(workflows.botId, botId),
          eq(workflows.name, name),
          eq(revisions.revision, revision ?? workflows.latestRevision),
        ),
      )
    return row
  },

  setEnabledRevision: (botId, name, revision, actorId, at) =>
    db.transaction(async (tx) => {
      const workflow = and(eq(workflows.botId, botId), eq(workflows.name, name))
      const [updated] = await tx
        .update(workflows)
        .set({
          enabledRevision: revision,
          scheduleCursor: revision === null ? null : at,
          updatedAt: sql`now()`,
        })
        .where(
          revision === null
            ? workflow
            : and(workflow, sql`${revision} between 1 and ${workflows.latestRevision}`),
        )
        .returning({ id: workflows.id })
      if (updated === undefined) return false
      await record(tx, botId, {
        workflowName: name,
        action: revision === null ? 'disable' : 'enable',
        revision,
        actorId,
      })
      return true
    }),

  deleteWorkflow: (botId, name, actorId) =>
    db.transaction(async (tx) => {
      const [deleted] = await tx
        .delete(workflows)
        .where(and(eq(workflows.botId, botId), eq(workflows.name, name)))
        .returning({ id: workflows.id })
      if (deleted === undefined) return false
      await record(tx, botId, { workflowName: name, action: 'delete', revision: null, actorId })
      return true
    }),

  enabledRevisions: (botId): Promise<ReadonlyArray<WorkflowRevision>> =>
    db
      .select(revisionColumns)
      .from(revisions)
      .innerJoin(
        workflows,
        and(
          eq(workflows.id, revisions.workflowId),
          eq(workflows.enabledRevision, revisions.revision),
        ),
      )
      .where(
        botId === undefined ? isNotNull(workflows.enabledRevision) : eq(workflows.botId, botId),
      )
      .orderBy(workflows.botId, workflows.name),

  workflowChanges: (botId, limit) =>
    db
      .select({
        workflowName: changes.workflowName,
        action: changes.action,
        revision: changes.revision,
        actorId: changes.actorId,
        at: changes.at,
      })
      .from(changes)
      .where(eq(changes.botId, botId))
      .orderBy(desc(changes.id))
      .limit(limit),

  scheduledWorkflows: () =>
    db
      .select({
        botId: workflows.botId,
        name: workflows.name,
        revision: revisions.revision,
        schedules: revisions.schedules,
        cursor: workflows.scheduleCursor,
      })
      .from(revisions)
      .innerJoin(
        workflows,
        and(
          eq(workflows.id, revisions.workflowId),
          eq(workflows.enabledRevision, revisions.revision),
        ),
      )
      .where(sql`jsonb_array_length(${revisions.schedules}) > 0`)
      .orderBy(workflows.botId, workflows.name)
      // Enabling a revision always sets its cursor.
      .then((rows) =>
        rows.flatMap(({ cursor, ...row }) => (cursor === null ? [] : [{ ...row, cursor }])),
      ),

  advanceScheduleCursor: async ({ botId, name, revision }, from, to) => {
    const [advanced] = await db
      .update(workflows)
      .set({ scheduleCursor: to })
      .where(
        and(
          eq(workflows.botId, botId),
          eq(workflows.name, name),
          eq(workflows.enabledRevision, revision),
          eq(workflows.scheduleCursor, from),
        ),
      )
      .returning({ id: workflows.id })
    return advanced !== undefined
  },

  lockSchedules: (botId) => locks.lock(scheduleLock(botId)),
  unlockSchedules: (botId) => locks.unlock(scheduleLock(botId)),

  loadWorkflowValue: async (workflowId, key) => {
    const [row] = await failing(
      'Reading a KV value',
      db
        .select({ value: kv.value })
        .from(kv)
        .where(and(eq(kv.workflowId, workflowId), eq(kv.key, key))),
    )
    return row?.value
  },

  storeWorkflowValue: (workflowId, key, value, limitBytes) =>
    failing(
      'Storing a KV value',
      db.transaction(async (tx) => {
        // Locking the workflow's row makes its writes take turns, so each sees the others' bytes.
        const [workflow] = await tx
          .select({ id: workflows.id })
          .from(workflows)
          .where(eq(workflows.id, workflowId))
          .for('update')
        if (workflow === undefined) throw new Error(`Workflow ${workflowId} no longer exists.`)
        const [others] = await tx
          .select({
            bytes: sql<string>`coalesce(sum(octet_length(${kv.key}) + octet_length(${kv.value})), 0)`,
          })
          .from(kv)
          .where(and(eq(kv.workflowId, workflowId), ne(kv.key, key)))
        const bytes = Number(others?.bytes ?? 0) + Buffer.byteLength(key) + Buffer.byteLength(value)
        if (bytes > limitBytes) return { stored: false, bytes }
        await tx
          .insert(kv)
          .values({ workflowId, key, value })
          .onConflictDoUpdate({
            target: [kv.workflowId, kv.key],
            set: { value, updatedAt: sql`now()` },
          })
        return { stored: true, bytes }
      }),
    ),

  deleteWorkflowValue: async (workflowId, key) => {
    await failing(
      'Deleting a KV value',
      db.delete(kv).where(and(eq(kv.workflowId, workflowId), eq(kv.key, key))),
    )
  },

  recordWorkflowRun: async (run, keep) => {
    await failing(
      'Recording a run',
      db.transaction(async (tx) => {
        // Recordings of one workflow take turns, so each trim sees the runs recorded before it.
        await tx
          .select({ id: workflows.id })
          .from(workflows)
          .where(eq(workflows.id, run.workflowId))
          .for('update')
        await tx.insert(runs).values(run)
        // The run ranked `keep + 1`, newest first, and every older one go, through the workflow's
        // (workflow_id, id) index.
        const [cutoff] = await tx
          .select({ id: runs.id })
          .from(runs)
          .where(eq(runs.workflowId, run.workflowId))
          .orderBy(desc(runs.id))
          .offset(keep)
          .limit(1)
        if (cutoff !== undefined) {
          await tx
            .delete(runs)
            .where(and(eq(runs.workflowId, run.workflowId), lte(runs.id, cutoff.id)))
        }
      }),
    )
  },

  workflowRuns: (botId, { name, failed, since, limit }) =>
    db
      .select({
        id: runs.id,
        workflowName: workflows.name,
        revision: runs.revision,
        event: runs.event,
        outcome: runs.outcome,
        error: runs.error,
        logs: runs.logs,
        receivedAt: runs.receivedAt,
        finishedAt: runs.finishedAt,
      })
      .from(runs)
      .innerJoin(workflows, eq(workflows.id, runs.workflowId))
      .where(
        and(
          eq(workflows.botId, botId),
          name === undefined ? undefined : eq(workflows.name, name),
          failed ? ne(runs.outcome, 'completed') : undefined,
          gte(runs.finishedAt, since),
        ),
      )
      .orderBy(desc(runs.id))
      .limit(limit),

  pruneWorkflowRuns: async (before) => {
    const deleted = await db
      .delete(runs)
      .where(lt(runs.finishedAt, before))
      .returning({ id: runs.id })
    return deleted.length
  },

  setVoiceOptOut: (scope, userId, optedOut) =>
    db.transaction(async (tx) => {
      if ('everywhere' in scope) {
        await (optedOut
          ? tx.insert(voiceGlobalOptOuts).values({ userId }).onConflictDoNothing()
          : tx.delete(voiceGlobalOptOuts).where(eq(voiceGlobalOptOuts.userId, userId)))
      } else {
        const { botId, guildId } = scope
        await (optedOut
          ? tx.insert(voiceOptOuts).values({ botId, guildId, userId }).onConflictDoNothing()
          : tx
              .delete(voiceOptOuts)
              .where(
                and(
                  eq(voiceOptOuts.botId, botId),
                  eq(voiceOptOuts.guildId, guildId),
                  eq(voiceOptOuts.userId, userId),
                ),
              ))
      }
      // Delivered to every listening process when the transaction commits.
      const change = JSON.stringify({ scope, userId, optedOut })
      await tx.execute(sql`select pg_notify(${VOICE_OPT_OUTS_CHANNEL}, ${change})`)
    }),

  voiceOptedOut: async (botId, guildId, userId) => {
    const found = await db
      .select({ userId: voiceGlobalOptOuts.userId })
      .from(voiceGlobalOptOuts)
      .where(eq(voiceGlobalOptOuts.userId, userId))
      .unionAll(
        db
          .select({ userId: voiceOptOuts.userId })
          .from(voiceOptOuts)
          .where(
            and(
              eq(voiceOptOuts.botId, botId),
              eq(voiceOptOuts.guildId, guildId),
              eq(voiceOptOuts.userId, userId),
            ),
          ),
      )
      .limit(1)
    return found.length > 0
  },

  watchVoiceOptOuts: ({ changed, missed, lost }) =>
    listen(VOICE_OPT_OUTS_CHANNEL, {
      payload: (payload) => changed(JSON.parse(payload) as VoiceOptOutChange),
      resumed: missed,
      lost,
    }),

  close: async () => {
    await locks.close()
    await close()
  },
})
