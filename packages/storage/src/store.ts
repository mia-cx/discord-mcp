import { fileURLToPath } from 'node:url'
import {
  and,
  desc,
  eq,
  getTableColumns,
  gt,
  gte,
  inArray,
  isNotNull,
  like,
  lt,
  lte,
  ne,
  sql,
} from 'drizzle-orm'
import type { PgDatabase, PgQueryResultHKT } from 'drizzle-orm/pg-core'
import type { Fence, Storage, WorkflowChange, WorkflowRevision } from './index.ts'
import type { AdvisoryLocks } from './locks.ts'
import * as schema from './schema.ts'

/** Drizzle wraps driver errors in "Failed query"; the driver's own message says what went wrong. */
export const rootMessage = (error: unknown): string =>
  error instanceof Error && error.cause !== undefined ? rootMessage(error.cause) : String(error)

/**
 * `query`, failing with only the driver's message. Drizzle's own lists the query parameters,
 * which hold what workflows wrote: KV keys and values, and run logs.
 */
const failing = <A>(what: string, query: PromiseLike<A>): Promise<A> =>
  Promise.resolve(query).catch((cause: unknown) => {
    throw new Error(`${what} failed: ${rootMessage(cause)}`)
  })

/** Checked-in SQL generated by `pnpm --filter @discord-mcp/storage generate`. */
export const migrationsFolder = fileURLToPath(new URL('../drizzle', import.meta.url))

type Db = PgDatabase<PgQueryResultHKT, typeof schema>

const { bots, shardSessions: sessions, leases } = schema
const {
  workflows,
  workflowRevisions: revisions,
  workflowChanges: changes,
  workflowKv: kv,
  workflowRuns: runs,
} = schema

const revisionColumns = {
  workflowId: workflows.id,
  botId: workflows.botId,
  name: workflows.name,
  revision: revisions.revision,
  source: revisions.source,
  bundle: revisions.bundle,
  packages: revisions.packages,
  grants: revisions.grants,
  events: revisions.events,
  intents: revisions.intents,
  route: revisions.route,
  schedules: revisions.schedules,
  publishedBy: revisions.publishedBy,
  publishedAt: revisions.publishedAt,
}

const record = (
  db: Db,
  botId: string,
  change: Pick<WorkflowChange, 'workflowName' | 'action' | 'revision' | 'actorId'>,
) => db.insert(changes).values({ botId, ...change })

/** Advisory lock names, so other locks can never collide with the scheduler's. */
const scheduleLock = (botId: string) => `textile-schedules:${botId}`

const OFFLINE = { shardCount: null, gatewayUrl: null, onlineUntil: null, presence: null } as const

const online = ({
  shardCount,
  gatewayUrl,
  onlineUntil,
}: Pick<typeof bots.$inferSelect, 'shardCount' | 'gatewayUrl' | 'onlineUntil'>) =>
  shardCount === null || gatewayUrl === null || onlineUntil === null
    ? undefined
    : { shardCount, gatewayUrl, until: onlineUntil }

/** A bot's enabled workflows keep it online and decide its intents, so neither is stored. */
// Written out, since Drizzle leaves the columns of a selected subquery unqualified.
const held = sql<boolean>`exists (
  select 1 from workflows w where w.bot_id = bots.id and w.enabled_revision is not null
)`
const intents = sql<number>`coalesce((
  select bit_or(r.intents) from workflow_revisions r
  inner join workflows w on w.id = r.workflow_id and w.enabled_revision = r.revision
  where w.bot_id = bots.id
), 0)`.mapWith(Number)
const botColumns = { ...getTableColumns(bots), held, intents }

/**
 * `fence`'s lease row, locked for the statement that names it, so a claim that hands the lease to
 * another holder waits for the write, and a write waiting on that claim re-checks the holder.
 * One statement rather than a transaction, so the write and its check can't be split up.
 */
const lockedLease = ({ lease, holder }: Fence) => sql`held as (
  select 1 from ${leases} where ${leases.name} = ${lease} and ${leases.holder} = ${holder}
  for share
)`

export const createStorage = (
  db: Db,
  locks: AdvisoryLocks,
  close: () => Promise<void>,
): Storage => ({
  storeSealedToken: async (botId, sealedToken) => {
    try {
      await db.transaction(async (tx) => {
        await tx
          .insert(bots)
          .values({ id: botId, sealedToken })
          .onConflictDoUpdate({
            target: bots.id,
            set: { sealedToken, ...OFFLINE, rejectedCode: null, updatedAt: sql`now()` },
          })
        await tx.delete(sessions).where(eq(sessions.botId, botId))
      })
    } catch (cause) {
      // Drizzle's own message lists the query parameters, sealed token included.
      throw new Error(`Storing bot ${botId}'s token failed: ${rootMessage(cause)}`)
    }
  },
  loadBot: async (botId) => {
    const [row] = await db.select(botColumns).from(bots).where(eq(bots.id, botId))
    if (row === undefined) return undefined
    const { sealedToken, intents, held, presence, rejectedCode } = row
    return { sealedToken, intents, held, presence, rejectedCode, online: online(row) }
  },
  setBotOnline: (botId, { shardCount, gatewayUrl, until }) =>
    db.transaction(async (tx) => {
      await tx
        .update(bots)
        .set({ shardCount, gatewayUrl, onlineUntil: until, updatedAt: sql`now()` })
        .where(eq(bots.id, botId))
      // Left by a shard that wrote after the bot went offline; Discord ended it.
      await tx.delete(sessions).where(eq(sessions.botId, botId))
    }),
  keepBotOnline: async (botId, until) => {
    const kept = await db
      .update(bots)
      .set({ onlineUntil: until })
      .where(and(eq(bots.id, botId), isNotNull(bots.onlineUntil)))
      .returning({ id: bots.id })
    return kept.length > 0
  },
  setBotPresence: async (botId, presence) => {
    const set = await db
      .update(bots)
      .set({ presence })
      .where(and(eq(bots.id, botId), isNotNull(bots.onlineUntil)))
      .returning({ id: bots.id })
    return set.length > 0
  },
  setBotOffline: (botId, { idleAt, rejectedCode } = {}) =>
    db.transaction(async (tx) => {
      const ended = await tx
        .update(bots)
        .set({ ...OFFLINE, ...(rejectedCode && { rejectedCode }), updatedAt: sql`now()` })
        .where(
          and(
            eq(bots.id, botId),
            idleAt === undefined ? undefined : and(sql`not ${held}`, lte(bots.onlineUntil, idleAt)),
          ),
        )
        .returning({ id: bots.id })
      if (ended.length === 0) return false
      await tx.delete(sessions).where(eq(sessions.botId, botId))
      return true
    }),
  loadOnlineBots: async () => {
    const rows = await db.select(botColumns).from(bots).where(isNotNull(bots.onlineUntil))
    const stored = await db
      .select({
        botId: sessions.botId,
        shardId: sessions.shardId,
        sealedSession: sessions.sealedSession,
      })
      .from(sessions)
      .innerJoin(bots, eq(bots.id, sessions.botId))
      .where(isNotNull(bots.onlineUntil))
    return rows.flatMap((row) => {
      const bot = online(row)
      if (bot === undefined) return []
      const { id, sealedToken, intents, held, presence } = row
      const own = stored.filter((session) => session.botId === id)
      return [{ botId: id, sealedToken, intents, held, presence, ...bot, sessions: own }]
    })
  },
  storeSealedSession: async (botId, shardId, sealedSession, fence) => {
    try {
      await db.execute(sql`
        with ${lockedLease(fence)}
        insert into shard_sessions (bot_id, shard_id, sealed_session)
        select ${botId}, ${shardId}, ${sealedSession} from held
        on conflict (bot_id, shard_id)
        do update set sealed_session = excluded.sealed_session, updated_at = now()
      `)
    } catch (cause) {
      throw new Error(
        `Storing bot ${botId}'s shard ${shardId} session failed: ${rootMessage(cause)}`,
      )
    }
  },
  deleteSession: async (botId, shardId, fence) => {
    await db.execute(sql`
      with ${lockedLease(fence)}
      delete from shard_sessions
      where bot_id = ${botId} and shard_id = ${shardId} and exists (select 1 from held)
    `)
  },

  claimLease: async (name, holder, now, ttlMs) => {
    const [claimed] = await db
      .insert(leases)
      .values({ name, holder, expiresAt: now + ttlMs })
      .onConflictDoUpdate({
        target: leases.name,
        set: { holder, expiresAt: now + ttlMs },
        setWhere: sql`${leases.holder} = ${holder} or ${leases.expiresAt} <= ${now}`,
      })
      .returning({ holder: leases.holder, expiresAt: leases.expiresAt })
    if (claimed !== undefined) return claimed
    const [current] = await db
      .select({ holder: leases.holder, expiresAt: leases.expiresAt })
      .from(leases)
      .where(eq(leases.name, name))
    // Released between the two queries: free now, so the caller's next claim takes it.
    return current ?? { holder: '', expiresAt: now }
  },
  renewLeases: async (holder, names, now, ttlMs) => {
    if (names.length === 0) return []
    const renewed = await db
      .update(leases)
      .set({ expiresAt: now + ttlMs })
      .where(
        and(eq(leases.holder, holder), inArray(leases.name, [...names]), gt(leases.expiresAt, now)),
      )
      .returning({ name: leases.name })
    return renewed.map(({ name }) => name)
  },
  releaseLease: async (name, holder) => {
    await db.delete(leases).where(and(eq(leases.name, name), eq(leases.holder, holder)))
  },
  releaseLeases: async (holder) => {
    await db.delete(leases).where(eq(leases.holder, holder))
  },
  liveLeases: async (prefix, now) => {
    const live = await db
      .select({ name: leases.name })
      .from(leases)
      .where(
        and(like(leases.name, `${prefix.replace(/[\\%_]/g, '\\$&')}%`), gt(leases.expiresAt, now)),
      )
    return live.map(({ name }) => name)
  },

  publishWorkflow: ({ actorId, botId, name, ...revision }) =>
    db.transaction(async (tx) => {
      // The upsert locks the workflow's row, so concurrent publishes number their revisions in turn.
      const [workflow] = await tx
        .insert(workflows)
        .values({ botId, name, latestRevision: 1 })
        .onConflictDoUpdate({
          target: [workflows.botId, workflows.name],
          set: { latestRevision: sql`${workflows.latestRevision} + 1`, updatedAt: sql`now()` },
        })
        .returning({ id: workflows.id, revision: workflows.latestRevision })
      if (workflow === undefined) throw new Error(`Publishing workflow ${name} stored nothing.`)
      const [stored] = await tx
        .insert(revisions)
        .values({
          workflowId: workflow.id,
          revision: workflow.revision,
          publishedBy: actorId,
          ...revision,
        })
        .returning({ publishedAt: revisions.publishedAt })
      await record(tx, botId, {
        workflowName: name,
        action: 'publish',
        revision: workflow.revision,
        actorId,
      })
      return {
        workflowId: workflow.id,
        botId,
        name,
        revision: workflow.revision,
        publishedBy: actorId,
        publishedAt: stored?.publishedAt ?? new Date(),
        ...revision,
      }
    }),

  listWorkflows: (botId) =>
    db
      .select({
        name: workflows.name,
        latestRevision: workflows.latestRevision,
        enabledRevision: workflows.enabledRevision,
      })
      .from(workflows)
      .where(eq(workflows.botId, botId))
      .orderBy(workflows.name),

  loadWorkflowRevision: async (botId, name, revision) => {
    const [row] = await db
      .select(revisionColumns)
      .from(revisions)
      .innerJoin(workflows, eq(workflows.id, revisions.workflowId))
      .where(
        and(
          eq(workflows.botId, botId),
          eq(workflows.name, name),
          eq(revisions.revision, revision ?? workflows.latestRevision),
        ),
      )
    return row
  },

  setEnabledRevision: (botId, name, revision, actorId, at) =>
    db.transaction(async (tx) => {
      const workflow = and(eq(workflows.botId, botId), eq(workflows.name, name))
      const [updated] = await tx
        .update(workflows)
        .set({
          enabledRevision: revision,
          scheduleCursor: revision === null ? null : at,
          updatedAt: sql`now()`,
        })
        .where(
          revision === null
            ? workflow
            : and(workflow, sql`${revision} between 1 and ${workflows.latestRevision}`),
        )
        .returning({ id: workflows.id })
      if (updated === undefined) return false
      await record(tx, botId, {
        workflowName: name,
        action: revision === null ? 'disable' : 'enable',
        revision,
        actorId,
      })
      return true
    }),

  deleteWorkflow: (botId, name, actorId) =>
    db.transaction(async (tx) => {
      const [deleted] = await tx
        .delete(workflows)
        .where(and(eq(workflows.botId, botId), eq(workflows.name, name)))
        .returning({ id: workflows.id })
      if (deleted === undefined) return false
      await record(tx, botId, { workflowName: name, action: 'delete', revision: null, actorId })
      return true
    }),

  enabledRevisions: (botId): Promise<ReadonlyArray<WorkflowRevision>> =>
    db
      .select(revisionColumns)
      .from(revisions)
      .innerJoin(
        workflows,
        and(
          eq(workflows.id, revisions.workflowId),
          eq(workflows.enabledRevision, revisions.revision),
        ),
      )
      .where(
        botId === undefined ? isNotNull(workflows.enabledRevision) : eq(workflows.botId, botId),
      )
      .orderBy(workflows.botId, workflows.name),

  workflowChanges: (botId, limit) =>
    db
      .select({
        workflowName: changes.workflowName,
        action: changes.action,
        revision: changes.revision,
        actorId: changes.actorId,
        at: changes.at,
      })
      .from(changes)
      .where(eq(changes.botId, botId))
      .orderBy(desc(changes.id))
      .limit(limit),

  scheduledWorkflows: () =>
    db
      .select({
        botId: workflows.botId,
        name: workflows.name,
        revision: revisions.revision,
        schedules: revisions.schedules,
        cursor: workflows.scheduleCursor,
      })
      .from(revisions)
      .innerJoin(
        workflows,
        and(
          eq(workflows.id, revisions.workflowId),
          eq(workflows.enabledRevision, revisions.revision),
        ),
      )
      .where(sql`jsonb_array_length(${revisions.schedules}) > 0`)
      .orderBy(workflows.botId, workflows.name)
      // Enabling a revision always sets its cursor.
      .then((rows) =>
        rows.flatMap(({ cursor, ...row }) => (cursor === null ? [] : [{ ...row, cursor }])),
      ),

  advanceScheduleCursor: async ({ botId, name, revision }, from, to) => {
    const [advanced] = await db
      .update(workflows)
      .set({ scheduleCursor: to })
      .where(
        and(
          eq(workflows.botId, botId),
          eq(workflows.name, name),
          eq(workflows.enabledRevision, revision),
          eq(workflows.scheduleCursor, from),
        ),
      )
      .returning({ id: workflows.id })
    return advanced !== undefined
  },

  lockSchedules: (botId) => locks.lock(scheduleLock(botId)),
  unlockSchedules: (botId) => locks.unlock(scheduleLock(botId)),

  loadWorkflowValue: async (workflowId, key) => {
    const [row] = await failing(
      'Reading a KV value',
      db
        .select({ value: kv.value })
        .from(kv)
        .where(and(eq(kv.workflowId, workflowId), eq(kv.key, key))),
    )
    return row?.value
  },

  storeWorkflowValue: (workflowId, key, value, limitBytes) =>
    failing(
      'Storing a KV value',
      db.transaction(async (tx) => {
        // Locking the workflow's row makes its writes take turns, so each sees the others' bytes.
        const [workflow] = await tx
          .select({ id: workflows.id })
          .from(workflows)
          .where(eq(workflows.id, workflowId))
          .for('update')
        if (workflow === undefined) throw new Error(`Workflow ${workflowId} no longer exists.`)
        const [others] = await tx
          .select({
            bytes: sql<string>`coalesce(sum(octet_length(${kv.key}) + octet_length(${kv.value})), 0)`,
          })
          .from(kv)
          .where(and(eq(kv.workflowId, workflowId), ne(kv.key, key)))
        const bytes = Number(others?.bytes ?? 0) + Buffer.byteLength(key) + Buffer.byteLength(value)
        if (bytes > limitBytes) return { stored: false, bytes }
        await tx
          .insert(kv)
          .values({ workflowId, key, value })
          .onConflictDoUpdate({
            target: [kv.workflowId, kv.key],
            set: { value, updatedAt: sql`now()` },
          })
        return { stored: true, bytes }
      }),
    ),

  deleteWorkflowValue: async (workflowId, key) => {
    await failing(
      'Deleting a KV value',
      db.delete(kv).where(and(eq(kv.workflowId, workflowId), eq(kv.key, key))),
    )
  },

  recordWorkflowRun: async (run, keep) => {
    await failing(
      'Recording a run',
      db.transaction(async (tx) => {
        // Recordings of one workflow take turns, so each trim sees the runs recorded before it.
        await tx
          .select({ id: workflows.id })
          .from(workflows)
          .where(eq(workflows.id, run.workflowId))
          .for('update')
        await tx.insert(runs).values(run)
        // The run ranked `keep + 1`, newest first, and every older one go, through the workflow's
        // (workflow_id, id) index.
        const [cutoff] = await tx
          .select({ id: runs.id })
          .from(runs)
          .where(eq(runs.workflowId, run.workflowId))
          .orderBy(desc(runs.id))
          .offset(keep)
          .limit(1)
        if (cutoff !== undefined) {
          await tx
            .delete(runs)
            .where(and(eq(runs.workflowId, run.workflowId), lte(runs.id, cutoff.id)))
        }
      }),
    )
  },

  workflowRuns: (botId, { name, failed, since, limit }) =>
    db
      .select({
        id: runs.id,
        workflowName: workflows.name,
        revision: runs.revision,
        event: runs.event,
        outcome: runs.outcome,
        error: runs.error,
        logs: runs.logs,
        receivedAt: runs.receivedAt,
        finishedAt: runs.finishedAt,
      })
      .from(runs)
      .innerJoin(workflows, eq(workflows.id, runs.workflowId))
      .where(
        and(
          eq(workflows.botId, botId),
          name === undefined ? undefined : eq(workflows.name, name),
          failed ? ne(runs.outcome, 'completed') : undefined,
          gte(runs.finishedAt, since),
        ),
      )
      .orderBy(desc(runs.id))
      .limit(limit),

  pruneWorkflowRuns: async (before) => {
    const deleted = await db
      .delete(runs)
      .where(lt(runs.finishedAt, before))
      .returning({ id: runs.id })
    return deleted.length
  },

  close: async () => {
    await locks.close()
    await close()
  },
})
